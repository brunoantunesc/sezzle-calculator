import { act, cleanup, fireEvent, render, renderHook, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, describe, expect, it, vi } from 'vitest'
import '@testing-library/jest-dom/vitest'
import App from './App'
import { CalculationError } from './services/calculatorApi'
import { useCalculator } from './hooks/useCalculator'

afterEach(() => { cleanup(); localStorage.clear() })

describe('calculator input', () => {
 it('preserves decimal strings and prevents duplicate decimals', () => {
  const { result } = renderHook(() => useCalculator())
  act(() => { for (const key of ['.', '0', '5', '.', '2']) result.current.press(key) })
  expect(result.current.display).toBe('0.052')
 })
 it('supports sign, backspace, zero and clear', () => {
  const { result } = renderHook(() => useCalculator())
  act(() => { for (const key of ['1','2','sign','backspace']) result.current.press(key) })
  expect(result.current.display).toBe('-1')
  act(() => result.current.press('backspace'))
  expect(result.current.display).toBe('0')
  act(() => { result.current.press('sign'); result.current.press('5') })
  expect(result.current.display).toBe('-5')
  act(() => result.current.press('clear'))
  expect(result.current.display).toBe('0')
  expect(result.current.expression).toBe('')
 })
 it('replaces an operator before the next operand and waits for it', () => {
  const calculate = vi.fn().mockResolvedValue(6)
  const { result } = renderHook(() => useCalculator(calculate))
  act(() => { for (const key of ['8','add','multiply','=']) result.current.press(key) })
  expect(calculate).not.toHaveBeenCalled()
  expect(result.current.expression).toContain('×')
 })
 it('submits binary and unary operations without calculating locally', async () => {
  const calculate = vi.fn().mockResolvedValueOnce(6).mockResolvedValueOnce(2)
  const { result } = renderHook(() => useCalculator(calculate))
  await act(async () => { for (const key of ['2','multiply','3','=']) result.current.press(key) })
  expect(calculate).toHaveBeenNthCalledWith(1, { operation: 'multiply', operands: [2,3] })
  expect(result.current.display).toBe('6')
  act(() => result.current.press('4'))
  expect(result.current.display).toBe('4')
  await act(async () => result.current.press('sqrt'))
  expect(calculate).toHaveBeenNthCalledWith(2, { operation: 'sqrt', operands: [4] })
  expect(result.current.display).toBe('2')
 })
 it('chains sequentially and reuses the returned result', async () => {
  const calculate = vi.fn().mockResolvedValueOnce(5).mockResolvedValueOnce(20)
  const { result } = renderHook(() => useCalculator(calculate))
  await act(async () => { for (const key of ['2','add','3','multiply']) result.current.press(key) })
  expect(result.current.display).toBe('5')
  await act(async () => { result.current.press('4'); result.current.press('=') })
  expect(calculate).toHaveBeenLastCalledWith({ operation: 'multiply', operands: [5,4] })
  expect(result.current.display).toBe('20')
 })
 it('ignores all input including clear while a request is pending', async () => {
  let resolve!: (value: number) => void
  const calculate = vi.fn(() => new Promise<number>(done => { resolve = done }))
  const { result } = renderHook(() => useCalculator(calculate))
  act(() => { for (const key of ['9','sqrt','=','1']) result.current.press(key) })
  expect(calculate).toHaveBeenCalledTimes(1)
  expect(result.current.pending).toBe(true)
  act(() => { result.current.press('clear'); result.current.press('7'); result.current.press('sqrt') })
  expect(result.current.display).toBe('9')
  expect(calculate).toHaveBeenCalledTimes(1)
  await act(async () => resolve(3))
  expect(result.current.display).toBe('3')
  expect(result.current.pending).toBe(false)
 })
 it('handles failures and non-finite responses safely', async () => {
  const calculate = vi.fn().mockRejectedValueOnce(new Error('internal details')).mockResolvedValueOnce(Infinity)
  const { result } = renderHook(() => useCalculator(calculate))
  await act(async () => result.current.press('sqrt'))
  expect(result.current.error).toBe('Unable to calculate. Please try again.')
  await act(async () => result.current.press('sqrt'))
  expect(result.current.error).toBe('Unable to calculate. Please try again.')
 })
})

describe('calculator interface', () => {
 it('supports mouse entry and keyboard pressed states', async () => {
  const user = userEvent.setup()
  render(<App calculate={vi.fn().mockResolvedValue(8)} />)
  await user.click(screen.getByRole('button', { name: '7' }))
  expect(screen.getByLabelText('Calculator display')).toHaveTextContent('7')
  fireEvent.keyDown(window, { key: '8' })
  expect(screen.getByRole('button', { name: '8' })).toHaveClass('is-pressed')
  expect(screen.getByLabelText('Calculator display')).toHaveTextContent('78')
  fireEvent.keyUp(window, { key: '8' })
  expect(screen.getByRole('button', { name: '8' })).not.toHaveClass('is-pressed')
  fireEvent.keyDown(window, { key: 'Backspace' })
  expect(screen.getByLabelText('Calculator display')).toHaveTextContent('7')
  fireEvent.keyDown(window, { key: 'Escape' })
  expect(screen.getByLabelText('Calculator display')).toHaveTextContent('0')
 })
 it('maps operators and Enter without a disconnected message', async () => {
  render(<App calculate={vi.fn().mockResolvedValue(8)} />)
  for (const key of ['2','^','3']) fireEvent.keyDown(window, { key })
  expect(screen.getByRole('button', { name: 'Power' })).toHaveClass('is-pressed')
  await act(async () => { fireEvent.keyDown(window, { key: 'Enter' }) })
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  fireEvent.blur(window)
  expect(screen.getByRole('button', { name: 'Power' })).not.toHaveClass('is-pressed')
 })
 it('lets a focused key activate with Enter without also submitting equals', async () => {
  const user = userEvent.setup()
  render(<App calculate={vi.fn().mockResolvedValue(8)} />)
  screen.getByRole('button', { name: '4' }).focus()
  await user.keyboard('{Enter}')
  expect(screen.getByLabelText('Calculator display')).toHaveTextContent('4')
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
 })
})

it('can take a square root of the second operand without losing the binary operation', async () => {
 const calculate = vi.fn().mockResolvedValueOnce(3).mockResolvedValueOnce(5)
 const { result } = renderHook(() => useCalculator(calculate))
 await act(async () => { for (const key of ['2','add','9','sqrt']) result.current.press(key) })
 expect(result.current.display).toBe('3')
 await act(async () => result.current.press('='))
 expect(calculate).toHaveBeenLastCalledWith({operation:'add',operands:[2,3]})
 expect(result.current.display).toBe('5')
})

it('reuses results with an operator and limits entry to 16 digits', async () => {
 const calculate = vi.fn().mockResolvedValue(3)
 const { result } = renderHook(() => useCalculator(calculate))
 await act(async () => { for (const key of ['9','sqrt']) result.current.press(key) })
 act(() => { result.current.press('add'); result.current.press('2') })
 await act(async () => result.current.press('='))
 expect(calculate).toHaveBeenLastCalledWith({operation:'add',operands:[3,2]})
 act(() => { result.current.press('clear'); for (let i=0;i<20;i++) result.current.press('9') })
 expect(result.current.display).toBe('9999999999999999')
})

it('opens a modal drawer and closes with Escape without clearing input', async () => {
 const user=userEvent.setup()
 render(<App />)
 await user.click(screen.getByRole('button',{name:'7'}))
 await user.click(screen.getByRole('button',{name:'History'}))
 expect(screen.getByRole('dialog',{name:'Calculation history'})).toHaveTextContent('No calculations yet.')
 await user.keyboard('123{Escape}')
 await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
 expect(screen.getByLabelText('Calculator display')).toHaveTextContent('7')
 await user.click(screen.getByRole('button',{name:'History'}))
 await user.click(screen.getByRole('button',{name:'Close history'}))
 await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
 await user.click(screen.getByRole('button',{name:'History'}))
 fireEvent.click(document.querySelector('.MuiBackdrop-root')!)
 await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
 expect(screen.getByLabelText('Calculator display')).toHaveTextContent('7')
})

it('shows parsed errors in a dismissible notice while preserving input', async () => {
 const user=userEvent.setup()
 render(<App calculate={vi.fn().mockRejectedValue(new CalculationError('Cannot divide by zero'))} />)
 for(const name of ['1','Divide','0','Equals']) await user.click(screen.getByRole('button',{name}))
 expect(await screen.findByRole('alert')).toHaveTextContent('Cannot divide by zero')
 expect(screen.getByLabelText('Calculator display')).toHaveTextContent('0')
 await user.click(screen.getByRole('button',{name:'Dismiss error'}))
 expect(screen.queryByRole('alert')).not.toBeInTheDocument()
})

it('records successful calculations, reuses results and clears history', async () => {
 const user=userEvent.setup()
 render(<App calculate={vi.fn().mockResolvedValue(5)} />)
 for(const name of ['2','Add','3','Equals']) await user.click(screen.getByRole('button',{name}))
 await user.click(screen.getByRole('button',{name:'History'}))
 expect(screen.getByRole('dialog')).toHaveTextContent('2 + 3')
 await user.click(screen.getByRole('button',{name:'Reuse result 5'}))
 await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
 expect(screen.getByLabelText('Calculator display')).toHaveTextContent('5')
 await user.click(screen.getByRole('button',{name:'History'}))
 await user.click(screen.getByRole('button',{name:'Clear history'}))
 expect(screen.getByRole('dialog')).toHaveTextContent('No calculations yet.')
 expect(JSON.parse(localStorage.getItem('calculator-history')!)).toEqual([])
})
